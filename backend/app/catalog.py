def seed_catalog(db):
    for title, artist, album, family, mood, energy, duration, art in ROWS:
        db.execute(
            """INSERT OR IGNORE INTO tracks
          (title,artist,normalized_key,album,genres,moods,energy,valence,family,art,duration)
          VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
            (
                title,
                artist,
                track_key(artist, title),
                album,
                json.dumps(GENRE_TAGS[family]),
                json.dumps(
                    [
                        mood,
                        "chill"
                        if energy < 0.5
                        else "energy"
                        if energy > 0.72
                        else "focus",
                    ]
                ),
                energy,
                0.65 if energy > 0.6 else 0.45,
                family,
                f"/art/cover-{art}.svg",
                duration,
            ),
        )



def seed_demo_history(db, user_id):
    from datetime import datetime, timedelta, timezone

    for index, (artist, title) in enumerate(DEMO_FAVORITES):
        row = db.execute(
            "SELECT id FROM tracks WHERE normalized_key=?", (track_key(artist, title),)
        ).fetchone()
        for play in range(max(2, 11 - index)):
            listened = (
                datetime.now(timezone.utc)
                - timedelta(days=play * 3 + index, hours=index % 8)
            ).isoformat()
            db.execute(
                "INSERT OR IGNORE INTO history(user_id,track_id,listened_at,event_key) VALUES(?,?,?,?)",
                (user_id, row["id"], listened, f"demo:{index}:{play}"),
            )
